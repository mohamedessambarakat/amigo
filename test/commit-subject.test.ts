  it('takeCommitSubject reads at most 512 bytes, decodes UTF-16 with a BOM, and refuses other binary text clearly', () => {
    const { dir, env } = makeHome();
    try {
      const file = join(env.AMIGO_HOME as string, 'state', 'tasks', 'x-1', 'commit-subject.txt');
      mkdirSync(join(env.AMIGO_HOME as string, 'state', 'tasks', 'x-1'), { recursive: true });
      const take = (bytes: Buffer) => {
        writeFileSync(file, bytes);
        const r = takeCommitSubject('x-1', env);
        assert.ok(!existsSync(file), 'removed once read');
        return r;
      };
      assert.deepEqual(take(Buffer.from('fix: plain\r\nmore\n')), { subject: 'fix: plain' });
      assert.deepEqual(take(Buffer.from('\ufefffix: utf8 bom\n')), { subject: 'fix: utf8 bom' });
      assert.deepEqual(take(Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from('fix: powershell\r\n', 'utf16le')])), { subject: 'fix: powershell' });
      const be = Buffer.from('fix: big endian\n', 'utf16le').swap16();
      assert.deepEqual(take(Buffer.concat([Buffer.from([0xfe, 0xff]), be])), { subject: 'fix: big endian' });
      const huge = take(Buffer.from('x'.repeat(10_000_000)));
      assert.ok(huge?.subject && huge.subject.length <= 512, 'only the first 512 bytes are read');
      const nul = take(Buffer.from('fix: no bom', 'utf16le'));
      assert.equal(nul?.subject, undefined);
      assert.match(nul?.problem ?? '', /save it as UTF-8/);
      assert.ok(!nul?.problem?.includes('\0'), 'no NUL in the message');
      assert.equal(takeCommitSubject('x-1', env), null, 'no file');
    } finally {
      cleanup(dir);
    }
  });

