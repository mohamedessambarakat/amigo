import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, it } from 'node:test';
import { checkCommitMessage } from '../src/commit.ts';
import { codeRoot } from '../src/paths.ts';

describe('commit subjects', () => {
  it('accepts type: summary and type(scope): summary, at most 50 chars', () => {
    for (const ok of ['fix: keep task ages when migrating', 'feat(close): check commit subjects', 'docs: add a note\n\nThe old one was wrong.', `chore: ${'x'.repeat(43)}`]) {
      assert.equal(checkCommitMessage(ok), null, ok);
    }
  });

  it('refuses anything else with the reason', () => {
    const cases: [string, RegExp][] = [
      ['', /empty/],
      ['Fix failing CI on amigo main', /must start with a type/],
      ['feature: add a thing', /must start with a type/],
      ['Fix: add a thing', /must start with a type/],
      ['fix(Auth): add a thing', /must start with a type/],
      ['fix:add a thing', /must start with a type/],
      ['fix: ', /must start with a type/],
      [`chore: ${'x'.repeat(44)}`, /51 chars, over the 50/],
      ['fix: add a thing \u2014 fast', /em dash/],
      ['fix: add a thing\n\nline one\nline two', /one line/],
      ['fix: add a thing\n\nCo-authored-by: Bot <b@x>', /co-author/],
      ['fix: add a thing\n\nGenerated by an agent', /generated by/],
    ];
    for (const [msg, re] of cases) assert.match(checkCommitMessage(msg) ?? '', re, JSON.stringify(msg));
  });

  it('README.md, prompts/amigo.md and prompts/member.md stay free of em dashes', () => {
    for (const rel of ['README.md', 'prompts/amigo.md', 'prompts/member.md']) {
      const text = readFileSync(join(codeRoot, rel), 'utf8');
      assert.ok(!text.includes('\u2014'), `${rel} must not contain an em dash`);
    }
  });
});
