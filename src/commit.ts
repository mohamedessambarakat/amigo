/** The commit types amigo accepts, as in `type: imperative summary`. */
export const COMMIT_TYPES = ['feat', 'fix', 'refactor', 'docs', 'style', 'test', 'chore', 'perf', 'build', 'ci'] as const;
export const MAX_SUBJECT = 50;

const SUBJECT_RE = new RegExp(`^(${COMMIT_TYPES.join('|')})(\\([a-z0-9-]+\\))?: \\S.*$`);
export const SUBJECT_FORMAT = `"type: imperative summary" or "type(scope): imperative summary", at most ${MAX_SUBJECT} chars, type one of ${COMMIT_TYPES.join(', ')}`;

/**
 * Why a commit message breaks the user's commit rule, or null when it is fine: a `type: summary` subject of at most 50 chars,
 * then optionally a blank line and a one-line body; no em dash, no co-author or "generated by" lines.
 */
export function checkCommitMessage(message: string): string | null {
  const [subject = '', ...rest] = message.trim().split(/\r?\n/);
  if (!subject.trim()) return 'the subject is empty';
  if (!SUBJECT_RE.test(subject)) return `it must start with a type, as in ${SUBJECT_FORMAT}`;
  if (subject.length > MAX_SUBJECT) return `it is ${subject.length} chars, over the ${MAX_SUBJECT} allowed`;
  if (/\u2014/.test(message)) return 'it has an em dash: use a plain "-"';
  if (/^\s*co-authored-by:/im.test(message)) return 'it has a co-author line';
  if (/generated (by|with)/i.test(message)) return 'it has a "generated by" line';
  const body = rest.filter((l) => l.trim());
  if (body.length > 1) return 'the body may be one line only (and only when the why is not obvious)';
  if (body.length && rest[0]?.trim()) return 'a blank line must separate the subject from the body';
  return null;
}
